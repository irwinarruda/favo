type NoticeSection = {
  titles: string[];
  license: string;
  repository?: string;
  files: { name: string; text: string }[];
};

function readPackage(directory: string) {
  return JSON.parse(readFileSync(`${directory}/package.json`, 'utf8'));
}

function findDependency(name: string, from: string) {
  for (let directory = from; directory !== dirname(directory); directory = dirname(directory)) {
    const candidate = `${directory}/node_modules/${name}`;
    if (existsSync(`${candidate}/package.json`)) return realpathSync(candidate);
  }
  return undefined;
}

async function bundledPackages() {
  const { metafile } = await Bun.build({ entrypoints: ['apps/cli/src/main.ts'], target: 'bun', metafile: true });
  const inputs = Object.keys(metafile!.inputs);
  const pending = inputs.flatMap((input) => PackageRoot.exec(input)?.[1] ?? []).map((root) => realpathSync(root));
  const found = new Set<string>();
  for (const directory of pending) {
    if (found.has(directory)) continue;
    found.add(directory);
    const { dependencies, optionalDependencies } = readPackage(directory);
    for (const name of Object.keys({ ...dependencies, ...optionalDependencies })) {
      const dependency = findDependency(name, directory);
      if (dependency) pending.push(dependency);
    }
  }
  return [...found];
}

function licenseFilesOf(directory: string) {
  return readdirSync(directory, { withFileTypes: true })
    .filter((entry) => entry.isFile() && LicenseFile.test(entry.name))
    .map((entry) => ({ name: entry.name, text: readFileSync(`${directory}/${entry.name}`, 'utf8').trim() }))
    .sort((left, right) => left.name.localeCompare(right.name));
}

async function thirdPartyNotices() {
  const sections = new Map<string, NoticeSection>();
  for (const directory of await bundledPackages()) {
    const { name, version, license, repository } = readPackage(directory);
    const files = licenseFilesOf(directory);
    if (!license && files.length === 0) throw new Error(`${name} ${version} declares no license and ships none`);
    if (files.length === 0) console.log(`note: ${name} ${version} ships no license file, it only declares ${license}`);
    const key = JSON.stringify([license, files]);
    const fresh = { titles: [], license, repository: repository?.url ?? repository, files };
    const section: NoticeSection = sections.get(key) ?? fresh;
    section.titles.push(`${name} ${version}`);
    sections.set(key, section);
  }
  const rendered = [...sections.values()]
    .map((section) => ({ ...section, titles: section.titles.sort() }))
    .sort((left, right) => left.titles[0]!.localeCompare(right.titles[0]!))
    .map(({ titles, license, repository, files }) => {
      const texts = files.map(({ name, text }) => `### ${name}\n\n${Fence}text\n${text}\n${Fence}\n`);
      const missing = `This package ships no license file. Its package.json declares ${license}. Source: ${repository}\n`;
      return [`## ${titles.join(', ')}\n\nLicense: ${license}\n`, ...(texts.length > 0 ? texts : [missing])].join('\n');
    });
  return [
    '# Third-party notices\n\nfavo is MIT licensed. Its binaries also contain the software below. This file is generated by `scripts/package-release.ts`.\n',
    BunNotice,
    readFileSync('scripts/third-party-extras.md', 'utf8'),
    ...rendered,
  ].join('\n');
}

const missing = Binaries.filter((binary) => !existsSync(`dist/${binary}`));
if (missing.length > 0) throw new Error(`Missing ${missing.join(', ')}. Run: bun run build:all`);

rmSync(Release, { recursive: true, force: true });
mkdirSync(Release, { recursive: true });
const sums: string[] = [];
for (const binary of Binaries) {
  const compressed = Bun.gzipSync(await Bun.file(`dist/${binary}`).bytes(), { level: 9 });
  await Bun.write(`${Release}/${binary}.gz`, compressed);
  sums.push(`${new Bun.CryptoHasher('sha256').update(compressed).digest('hex')}  ${binary}.gz`);
}
await Bun.write(`${Release}/SHA256SUMS`, `${sums.join('\n')}\n`);
await Bun.write(`${Release}/THIRD-PARTY-NOTICES.md`, await thirdPartyNotices());
console.log(`wrote ${readdirSync(Release).sort().join(', ')} to ${Release}`);
